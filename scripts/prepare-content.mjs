import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createCatalog, serializeDocument, walk, posix } from './content.mjs';

export const projectRoot = fileURLToPath(new URL('../', import.meta.url));

async function writeIfChanged(filename, value) {
  const bytes = Buffer.isBuffer(value) ? value : Buffer.from(value);
  const previous = await fs.readFile(filename).catch(() => null);
  if (previous?.equals(bytes)) return;
  await fs.mkdir(path.dirname(filename), { recursive: true });
  await fs.writeFile(filename, bytes);
}

async function syncGenerated(directory, files) {
  await fs.mkdir(directory, { recursive: true });
  for (const filename of await walk(directory)) {
    if (!files.has(posix(path.relative(directory, filename)))) await fs.unlink(filename);
  }
  for (const [relative, value] of files) await writeIfChanged(path.join(directory, relative), value);
}

export async function prepareContent(root = projectRoot) {
  const contentDir = path.join(root, 'content');
  const catalog = await createCatalog(contentDir);
  const docs = new Map(catalog.published.map((entry) => [entry.source === 'README.md' ? 'index.md' : entry.source, serializeDocument(entry)]));
  await syncGenerated(path.join(root, 'src/content/docs'), docs);
  const assets = new Map(await Promise.all(catalog.assets.map(async (source) => [source, await fs.readFile(path.join(contentDir, source))])));
  await syncGenerated(path.join(root, 'public/content'), assets);
  await writeIfChanged(path.join(root, 'src/generated/sidebar.mjs'), `// Generated by prepare-content.mjs. Edit content/ instead.\nexport default ${JSON.stringify(catalog.sidebar, null, 2)};\n`);
  await writeIfChanged(path.join(root, 'src/generated/catalog.json'), JSON.stringify({
    counts: catalog.counts, total: catalog.total, hidden: catalog.hidden, assets: catalog.assets,
    published: catalog.published.map(({ source, title, route }) => ({ source, title, route })),
  }, null, 2) + '\n');
  await writeIfChanged(path.join(root, 'public/legacy-routes.json'), JSON.stringify(catalog.routes) + '\n');
  return catalog;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const catalog = await prepareContent();
  console.log(`Published ${catalog.total} articles + homepage; hidden ${catalog.hidden.length}.`, catalog.counts);
}
